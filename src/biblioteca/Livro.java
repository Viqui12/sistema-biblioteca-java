package biblioteca;

public class Livro {
	 String titulo;  // atributo da classe
	 String autor;
	 String isbn;
	 String editora;
	 int ano;
	 int quantidade;
	 boolean disponibilidade;
	 
	  public Livro(String titulo, String  autor , String isbn,String editora,  int ano, int quantidade, boolean disponibilidade )  {
		  this.titulo = titulo;
		  this.autor = autor;
		  this.isbn  = isbn;
		  this.editora = editora;
		  this.ano = ano;
		  this.quantidade = quantidade;
		  this.disponibilidade = disponibilidade;
		  
		  
		  
	  } // parâmetro do construtor
	  
	 

}
